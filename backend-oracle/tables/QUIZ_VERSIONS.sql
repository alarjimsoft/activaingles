--------------------------------------------------------
--  DDL for Table QUIZ_VERSIONS
--  Cada Word que sube el académico crea una versión. Los intentos apuntan a la versión
--  que el estudiante contestó, así una corrección posterior no altera calificaciones.
--  DEFINITION_JSON contiene las respuestas correctas: solo se entrega a FastAPI.
--------------------------------------------------------

CREATE TABLE QUIZ_VERSIONS (
    VERSION_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    QUIZ_ID             NUMBER         NOT NULL,
    VERSION_NUMBER      NUMBER         NOT NULL,
    STATUS              VARCHAR2(20)   DEFAULT 'BORRADOR' NOT NULL,
    TITLE               VARCHAR2(300),
    PASSING_SCORE       NUMBER(5,2),
    MAX_ATTEMPTS        NUMBER,
    TIME_LIMIT_MINUTES  NUMBER,
    TOTAL_POINTS        NUMBER(7,2),
    QUESTION_COUNT      NUMBER,
    DEFINITION_JSON     CLOB           NOT NULL,
    VALIDATION_JSON     CLOB,
    DOCX_OBJECT_KEY     VARCHAR2(500),
    UPLOADED_BY         VARCHAR2(20 CHAR),
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    PUBLISHED_AT        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_QUIZ_VERSIONS PRIMARY KEY (VERSION_ID),
    CONSTRAINT UQ_QUIZ_VERSIONS_NUM UNIQUE (QUIZ_ID, VERSION_NUMBER),
    CONSTRAINT CK_QV_STATUS CHECK (STATUS IN ('BORRADOR', 'PUBLICADA', 'ARCHIVADA')),
    CONSTRAINT CK_QV_DEFINITION_JSON CHECK (DEFINITION_JSON IS JSON),
    CONSTRAINT CK_QV_VALIDATION_JSON CHECK (VALIDATION_JSON IS JSON),
    CONSTRAINT CK_QV_PASSING CHECK (PASSING_SCORE BETWEEN 0 AND 100),
    CONSTRAINT CK_QV_ATTEMPTS CHECK (MAX_ATTEMPTS > 0),
    CONSTRAINT CK_QV_TIME CHECK (TIME_LIMIT_MINUTES > 0),
    CONSTRAINT FK_QV_QUIZ FOREIGN KEY (QUIZ_ID) REFERENCES QUIZZES (QUIZ_ID),
    CONSTRAINT FK_QV_ACADEMICO FOREIGN KEY (UPLOADED_BY) REFERENCES ACADEMICOS (ID_ACADEMICO)
);

ALTER TABLE QUIZZES ADD CONSTRAINT FK_QUIZZES_PUBLISHED
    FOREIGN KEY (PUBLISHED_VERSION_ID) REFERENCES QUIZ_VERSIONS (VERSION_ID);
