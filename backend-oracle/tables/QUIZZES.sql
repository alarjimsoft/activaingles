--  DDL for Table QUIZZES
--  Un quiz por posición en el curso: se presenta después del tema AFTER_TOPIC_ID.
--  La posición es un dato, no código: para agregar un quiz basta con insertar un registro.
--------------------------------------------------------

CREATE TABLE QUIZZES (
    QUIZ_ID               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    AFTER_TOPIC_ID        NUMBER         NOT NULL,
    TITLE                 VARCHAR2(200)  NOT NULL,
    PUBLISHED_VERSION_ID  NUMBER,
    IS_ACTIVE             CHAR(1)        DEFAULT 'Y' NOT NULL,
    CREATED_AT            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_QUIZZES PRIMARY KEY (QUIZ_ID),
    CONSTRAINT UQ_QUIZZES_TOPIC UNIQUE (AFTER_TOPIC_ID),
    CONSTRAINT CK_QUIZZES_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N')),
    CONSTRAINT FK_QUIZZES_TOPIC FOREIGN KEY (AFTER_TOPIC_ID) REFERENCES TOPICS (TOPIC_ID)
);

