--  DDL for Table QUIZ_ATTEMPTS
--  Un registro por intento. Cuenta el mejor intento: el XP del quiz es el máximo de
--  XP_EARNED entre los intentos ENTREGADO (ver progress/stats).
--  EN_CURSO -> ENTREGADO (lo califica FastAPI) o EXPIRADO (se acabó el tiempo sin entregar).
--------------------------------------------------------

CREATE TABLE QUIZ_ATTEMPTS (
    ATTEMPT_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    QUIZ_ID         NUMBER        NOT NULL,
    VERSION_ID      NUMBER        NOT NULL,
    ID_INSCRIPCION  NUMBER        NOT NULL,
    ATTEMPT_NUMBER  NUMBER        NOT NULL,
    STATUS          VARCHAR2(20)  DEFAULT 'EN_CURSO' NOT NULL,
    SHUFFLE_SEED    NUMBER        NOT NULL,
    STARTED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT      TIMESTAMP WITH TIME ZONE,
    SUBMITTED_AT    TIMESTAMP WITH TIME ZONE,
    SCORE_POINTS    NUMBER(7,2),
    MAX_POINTS      NUMBER(7,2),
    SCORE_PERCENT   NUMBER(5,2),
    PASSED          CHAR(1),
    XP_EARNED       NUMBER        DEFAULT 0 NOT NULL,
    CONSTRAINT PK_QUIZ_ATTEMPTS PRIMARY KEY (ATTEMPT_ID),
    CONSTRAINT UQ_QA_NUMBER UNIQUE (ID_INSCRIPCION, QUIZ_ID, ATTEMPT_NUMBER),
    CONSTRAINT CK_QA_STATUS CHECK (STATUS IN ('EN_CURSO', 'ENTREGADO', 'EXPIRADO')),
    CONSTRAINT CK_QA_PERCENT CHECK (SCORE_PERCENT BETWEEN 0 AND 100),
    CONSTRAINT CK_QA_PASSED CHECK (PASSED IN ('Y', 'N')),
    CONSTRAINT CK_QA_XP CHECK (XP_EARNED BETWEEN 0 AND 200),
    CONSTRAINT FK_QA_QUIZ FOREIGN KEY (QUIZ_ID) REFERENCES QUIZZES (QUIZ_ID),
    CONSTRAINT FK_QA_VERSION FOREIGN KEY (VERSION_ID) REFERENCES QUIZ_VERSIONS (VERSION_ID),
    CONSTRAINT FK_QA_INSCRIPCION FOREIGN KEY (ID_INSCRIPCION) REFERENCES INSCRIPCIONES (ID_INSCRIPCION)
);

CREATE INDEX IDX_QA_INSCRIPCION_QUIZ ON QUIZ_ATTEMPTS (ID_INSCRIPCION, QUIZ_ID);
CREATE INDEX IDX_QA_VERSION ON QUIZ_ATTEMPTS (VERSION_ID);
