--------------------------------------------------------
--  DDL for Table QUIZ_ANSWERS
--  Respuesta del estudiante a cada pregunta de un intento, ya calificada por FastAPI.
--  QUESTION_KEY (S1-P1, S1-P2...) es estable dentro de una versión; sirve para las
--  estadísticas por pregunta.
--  IS_CORRECT: Y = completa, P = parcial (relacionar, respuesta abierta), N = incorrecta.
--------------------------------------------------------

CREATE TABLE QUIZ_ANSWERS (
    ANSWER_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ATTEMPT_ID       NUMBER        NOT NULL,
    QUESTION_KEY     VARCHAR2(20)  NOT NULL,
    QUESTION_TYPE    VARCHAR2(20)  NOT NULL,
    STUDENT_ANSWER   CLOB,
    IS_CORRECT       CHAR(1)       DEFAULT 'N' NOT NULL,
    POINTS_EARNED    NUMBER(7,2)   DEFAULT 0 NOT NULL,
    POINTS_POSSIBLE  NUMBER(7,2)   NOT NULL,
    AI_FEEDBACK      CLOB,
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_QUIZ_ANSWERS PRIMARY KEY (ANSWER_ID),
    CONSTRAINT UQ_QANS_QUESTION UNIQUE (ATTEMPT_ID, QUESTION_KEY),
    CONSTRAINT CK_QANS_TYPE CHECK (QUESTION_TYPE IN ('multiple_choice', 'true_false', 'fill_blank', 'matching', 'open')),
    CONSTRAINT CK_QANS_CORRECT CHECK (IS_CORRECT IN ('Y', 'P', 'N')),
    CONSTRAINT CK_QANS_POINTS CHECK (POINTS_EARNED >= 0 AND POINTS_EARNED <= POINTS_POSSIBLE),
    CONSTRAINT FK_QANS_ATTEMPT FOREIGN KEY (ATTEMPT_ID) REFERENCES QUIZ_ATTEMPTS (ATTEMPT_ID) ON DELETE CASCADE
);
