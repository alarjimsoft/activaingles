--------------------------------------------------------
--  DDL for Table QUIZ_MEDIA
--  Imágenes y audios de cada versión. El archivo vive en Cloud Storage; aquí solo la ruta.
--  OBJECT_KEY se arma con el hash del contenido, así una versión nueva reutiliza los
--  archivos que no cambiaron y el académico no tiene que volver a subirlos.
--  IS_UPLOADED = 'N' mientras el académico no suba un archivo citado en el Word.
--------------------------------------------------------

CREATE TABLE QUIZ_MEDIA (
    MEDIA_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    VERSION_ID     NUMBER          NOT NULL,
    FILE_NAME      VARCHAR2(255)   NOT NULL,
    MEDIA_TYPE     VARCHAR2(10)    NOT NULL,
    OBJECT_KEY     VARCHAR2(500),
    URL            VARCHAR2(1000),
    CONTENT_TYPE   VARCHAR2(100),
    SIZE_BYTES     NUMBER,
    SHA256         VARCHAR2(64),
    IS_UPLOADED    CHAR(1)         DEFAULT 'N' NOT NULL,
    UPLOADED_AT    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_QUIZ_MEDIA PRIMARY KEY (MEDIA_ID),
    CONSTRAINT UQ_QUIZ_MEDIA_FILE UNIQUE (VERSION_ID, FILE_NAME),
    CONSTRAINT CK_QM_TYPE CHECK (MEDIA_TYPE IN ('IMAGE', 'AUDIO', 'VIDEO', 'LINK')),
    CONSTRAINT CK_QM_UPLOADED CHECK (IS_UPLOADED IN ('Y', 'N')),
    CONSTRAINT FK_QM_VERSION FOREIGN KEY (VERSION_ID) REFERENCES QUIZ_VERSIONS (VERSION_ID) ON DELETE CASCADE
);
